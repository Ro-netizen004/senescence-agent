"""Build a non-destructive, evidence-based registry of evaluation artifacts."""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RESULTS = ROOT / "eval" / "results" / "ablation"
CSV_PATH = RESULTS / "RESULTS_REGISTRY.csv"
MD_PATH = RESULTS / "RESULTS_INDEX.md"


def _records(payload):
    if isinstance(payload, dict):
        yield payload
        for key in ("permutations", "runs", "jobs", "results"):
            values = payload.get(key)
            if isinstance(values, list):
                for value in values:
                    if isinstance(value, dict):
                        yield value
    elif isinstance(payload, list):
        for value in payload:
            if isinstance(value, dict):
                yield value


def _kind(name: str, payload: dict) -> str:
    if name.startswith("agent_positive_"):
        return "positive_control"
    if "sweep_summary" in name:
        return "multi_tissue_summary"
    if "sweep_status" in name:
        return "multi_tissue_status"
    if name.startswith("agent_null_") and isinstance(payload.get("permutations"), list):
        return "null_sweep"
    return "supporting_or_diagnostic"


def _companion_files(path: Path) -> str:
    return ";".join(
        candidate.name
        for candidate in sorted(path.parent.glob(f"{path.stem}.*"))
        if candidate != path
    )


def classify(path: Path) -> dict:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeDecodeError) as exc:
        return {
            "artifact": path.name,
            "kind": "unreadable_json",
            "code_era": "unknown",
            "paper_status": "exclude",
            "has_analysis_plan": False,
            "has_replicate_stability": False,
            "arm": "",
            "design": "",
            "completed_runs": "",
            "companion_files": _companion_files(path),
            "reason": f"Could not parse JSON: {exc}",
        }

    root = payload if isinstance(payload, dict) else {}
    records = list(_records(payload))
    has_plan = any(bool(record.get("analysis_plan")) for record in records)
    has_stability = any(bool(record.get("replicate_stability")) for record in records)
    kind = _kind(path.stem, root)

    if has_plan:
        era = "post_planner"
        status = "current_candidate"
        reason = "Contains an analysis-plan audit; eligible after protocol/QC review."
    elif has_stability:
        era = "stability_gate_pre_planner"
        status = "development_only"
        reason = "Contains donor-stability evidence but predates analysis planning."
    else:
        era = "pre_planner_or_unverified_gate"
        status = "development_only"
        reason = "No analysis-plan audit; do not pool with current-agent results."

    if kind in {"multi_tissue_summary", "multi_tissue_status", "supporting_or_diagnostic"}:
        status = "supporting_only"
        reason = "Aggregate/support artifact; trace paper claims to its component runs."

    return {
        "artifact": path.name,
        "kind": kind,
        "code_era": era,
        "paper_status": status,
        "has_analysis_plan": has_plan,
        "has_replicate_stability": has_stability,
        "arm": root.get("arm", ""),
        "design": root.get("design", ""),
        "completed_runs": root.get("n_perm_completed", ""),
        "companion_files": _companion_files(path),
        "reason": reason,
    }


def build_registry():
    rows = [
        classify(path) for path in sorted(RESULTS.glob("*.json"))
        if path.name not in {CSV_PATH.name, MD_PATH.name}
    ]
    fields = [
        "artifact", "kind", "code_era", "paper_status",
        "has_analysis_plan", "has_replicate_stability", "arm", "design",
        "completed_runs", "companion_files", "reason",
    ]
    with CSV_PATH.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    by_status = Counter(row["paper_status"] for row in rows)
    grouped = defaultdict(list)
    for row in rows:
        grouped[row["paper_status"]].append(row)

    lines = [
        "# Evaluation Results Index", "",
        "Generated by `organize_results.py`. This registry is non-destructive: no",
        "result was moved, renamed, overwritten, or deleted.", "",
        "## Interpretation Rules", "",
        "- `current_candidate`: contains a post-planner analysis-plan audit. It may",
        "  enter the final paper set only after protocol and completeness review.",
        "- `development_only`: valid for the historical code version that produced",
        "  it, but must not be pooled with final post-planner evaluation runs.",
        "- `supporting_only`: aggregate, status, or diagnostic material. Trace any",
        "  scientific claim back to component run JSON.",
        "- `exclude`: unreadable or structurally unusable artifact.", "",
        "## Current Inventory", "",
    ]
    for status in ("current_candidate", "development_only", "supporting_only", "exclude"):
        lines.append(f"- {status}: **{by_status.get(status, 0)}** JSON artifacts")
    lines += [
        "", "## Critical Boundary", "",
        "Absence of `analysis_plan` means the artifact did not evaluate the current",
        "planner-enabled agent. Absence of `replicate_stability` means donor-stability",
        "licensing cannot be established from that artifact. Filenames and timestamps",
        "are not used as evidence of feature coverage.", "",
    ]
    for status in ("current_candidate", "development_only", "supporting_only", "exclude"):
        entries = grouped.get(status, [])
        if not entries:
            continue
        lines += [f"## {status.replace('_', ' ').title()}", "",
                  "| Artifact | Kind | Era | Stability | Runs |", "|---|---|---|---:|---:|"]
        for row in entries:
            lines.append(
                f"| `{row['artifact']}` | {row['kind']} | {row['code_era']} | "
                f"{row['has_replicate_stability']} | {row['completed_runs']} |"
            )
        lines.append("")
    MD_PATH.write_text("\n".join(lines), encoding="utf-8")
    return rows


if __name__ == "__main__":
    registry = build_registry()
    counts = Counter(row["paper_status"] for row in registry)
    print(f"Indexed {len(registry)} JSON artifacts: {dict(counts)}")
    print(f"Saved: {CSV_PATH}")
    print(f"Saved: {MD_PATH}")
